"""🎯 กฎการวางไพ่รูน — ขั้น 2 ของศึกไพ่รูน

ไฟล์นี้ตอบคำถามเดียว: **ไพ่ใบนี้วางทับกองตอนนี้ได้ไหม**
ไม่มีลำดับเทิร์น ไม่มีการจั่ว ไม่มีเงิน — เป็นขั้นถัด ๆ ไป

📐 กติกา (ตามสำรับ UNO จริง):
   1. สีตรงกับสีปัจจุบันของกอง = วางได้
   2. หน้าไพ่ตรงกัน (เลขเดียวกัน หรือท่าเดียวกัน) = วางได้ แม้คนละสี
   3. ไพ่ไวลด์วางทับอะไรก็ได้เสมอ
   4. นอกนั้นวางไม่ได้

⚠️ "สีปัจจุบันของกอง" ไม่เท่ากับ "สีของไพ่บนสุด" เสมอไป
   พอมีคนวางไวลด์ ไพ่บนสุดจะไม่มีสี (suit เป็น None) แต่คนวางเลือกสีไว้
   เกมจึงต้องจำสีที่เลือกแยกต่างหาก ไม่ใช่อ่านจากไพ่บนสุดอย่างเดียว
   นี่เป็นจุดที่พลาดกันบ่อย — วางไวลด์แล้วเกมค้างเพราะไม่มีสีให้เทียบ

🔒 ทุกอย่างในไฟล์นี้เป็นฟังก์ชันล้วน (ไม่แตะฐานข้อมูล ไม่จำสถานะ)
   เซิร์ฟเวอร์เป็นคนเรียกใช้ตัดสิน เบราว์เซอร์ห้ามตัดสินเอง
"""
from bot.games.casino.uno import deck as D


def playable(card, top, active_suit=None):
    """ไพ่ใบนี้วางทับกองตอนนี้ได้ไหม

    card        ไพ่ที่จะวาง
    top         ไพ่บนสุดของกองทิ้ง
    active_suit สีที่ใช้อยู่จริง — ใส่มาเมื่อไพ่บนสุดเป็นไวลด์ที่เลือกสีไว้แล้ว
                ไม่ใส่ = ใช้สีของไพ่บนสุดเอง
    """
    if card is None or top is None:
        return False
    if D.is_wild(card):
        return True                          # ไวลด์วางทับอะไรก็ได้
    suit = active_suit or top.get("suit")
    if suit and card["suit"] == suit:
        return True                          # สีตรง
    return card["value"] == top["value"]     # หน้าไพ่ตรง (เลขหรือท่าเดียวกัน)


def playable_cards(hand, top, active_suit=None):
    """ไพ่ในมือใบไหนวางได้บ้าง — ไว้ให้หน้าเว็บหรี่ใบที่วางไม่ได้"""
    return [c for c in (hand or []) if playable(c, top, active_suit)]


def has_play(hand, top, active_suit=None):
    """มีไพ่วางได้สักใบไหม — ไม่มีก็ต้องจั่ว"""
    return any(playable(c, top, active_suit) for c in (hand or []))


def suit_after(card, chosen=None):
    """วางใบนี้แล้วสีของกองกลายเป็นอะไร

    ไพ่ไวลด์: ใช้สีที่คนวางเลือก (chosen) — เลือกมั่วหรือไม่เลือก = ยังไม่มีสี
    ไพ่ปกติ: สีของไพ่นั้นเอง
    """
    if D.is_wild(card):
        return chosen if chosen in D.SUITS else None
    return card["suit"]


def needs_colour_choice(card):
    """วางใบนี้แล้วต้องให้คนวางเลือกสีต่อไหม"""
    return D.is_wild(card)


def draw_penalty(card):
    """วางใบนี้แล้วคนถัดไปต้องจั่วกี่ใบ (0 = ไม่ต้องจั่ว)"""
    if card["value"] == D.DRAW_TWO:
        return 2
    if card["value"] == D.WILD_DRAW_FOUR:
        return 4
    return 0


def can_start_pile(card):
    """ไพ่ใบนี้ใช้เป็นใบแรกของกองทิ้งได้ไหม

    ⚠️ ไพ่ท่าพิเศษเปิดเกมไม่ได้ — ยังไม่มีใครเป็น "คนถัดไป" ให้โดนท่านั้น
       เปิดมาเป็น +4 ตั้งแต่ใบแรกคือเกมเริ่มด้วยการลงโทษคนที่ยังไม่ได้ทำอะไร
       (uno-engine ก็ทำแบบเดียวกัน: จั่วใหม่จนกว่าจะได้ไพ่ตัวเลข)
    """
    return not D.is_action(card)
