"""🎯 กฎการทาย — ขั้น 1 ของเกมทายเลข 1-10

ไฟล์นี้ตอบคำถามเดียว: **ทายเลขนี้แล้วได้ผลอะไร**
ไม่มีลำดับเทิร์น ไม่มีผู้เล่น ไม่มี state ค้าง — ขั้นถัดไปอยู่ที่ engine.py

📐 กติกา
   1. เลขลับอยู่ระหว่าง 1-10 (สุ่มโดยเซิร์ฟเวอร์)
   2. ทายตรงเป๊ะ = ถูก ชนะทันที
   3. ทายผิด = บอกแค่ "สูงไป" (เลขลับต่ำกว่าที่ทาย) หรือ "ต่ำไป" (เลขลับสูงกว่าที่ทาย)

🔒 ทุกอย่างในไฟล์นี้เป็นฟังก์ชันล้วน (ไม่แตะฐานข้อมูล ไม่จำสถานะ)
   เซิร์ฟเวอร์ (engine.py) เป็นคนเรียกใช้ตัดสิน เบราว์เซอร์ห้ามตัดสินเอง
   ตัวอย่างจริงที่ทำตามแบบนี้: bot/games/casino/uno/rules.py
"""
MIN_NUM = 1
MAX_NUM = 10


def valid_guess(n):
    """เลขนี้อยู่ในช่วงที่ทายได้ไหม — กันของแปลก ๆ ที่หลุดมาจากเบราว์เซอร์"""
    try:
        n = int(n)
    except (TypeError, ValueError):
        return False
    return MIN_NUM <= n <= MAX_NUM


def feedback(secret, guess):
    """ทายเลขนี้เทียบกับเลขลับ ได้ผลอะไร — "correct" | "higher" | "lower"

    higher = เลขลับ**สูงกว่า**ที่ทาย (ต้องทายเลขที่สูงขึ้นในตาถัดไป)
    lower  = เลขลับ**ต่ำกว่า**ที่ทาย (ต้องทายเลขที่ต่ำลงในตาถัดไป)
    """
    if guess == secret:
        return "correct"
    return "higher" if secret > guess else "lower"
